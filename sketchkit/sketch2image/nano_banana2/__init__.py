"""Nano Banana 2 - Google Gemini API for sketch-to-image conversion."""

import os
from typing import Union, Tuple, Optional
from PIL import Image

try:
    from google import genai
    GENAI_AVAILABLE = True
except ImportError:
    GENAI_AVAILABLE = False
    genai = None


class NanoBanana2Model:
    """Nano Banana 2 model using Google Gemini API.
    
    Note:
        API key must be set in ~/.sketchkit/config as GOOGLE_API_KEY="your_api_key"
    """
    
    def __init__(self, device: str = "cuda", model_name: str = "gemini-3.1-flash-image-preview", **kwargs):
        if not GENAI_AVAILABLE:
            raise ImportError("google-generativeai not installed. Run: pip install google-generativeai")
        
        api_key = os.environ.get('GOOGLE_API_KEY')
        if not api_key:
            raise ValueError("GOOGLE_API_KEY not found. Please add it to ~/.sketchkit/config")
        
        self.model_name = model_name
        self.device = device
        self.client = genai.Client(api_key=api_key)
    
    def generate(self, control_image: Image.Image, prompt: str, 
                 size: Optional[Union[int, Tuple[int, int]]] = None,
                 negative_prompt: Optional[str] = None, **kwargs) -> Image.Image:
        """Generate image from sketch using Google Gemini API."""
        
        full_prompt = f"{prompt}. Avoid: {negative_prompt}" if negative_prompt else prompt
        
        if control_image.mode != 'RGB':
            control_image = control_image.convert('RGB')
        
        if size:
            target_size = (size, size) if isinstance(size, int) else tuple(size)
            control_image = control_image.resize(target_size, Image.Resampling.LANCZOS)
        
        response = self.client.models.generate_content(
            model=self.model_name,
            contents=[full_prompt, control_image]
        )
        
        for part in response.parts:
            if part.inline_data:
                return part.as_image()
        
        raise RuntimeError("No image generated by Gemini API")
